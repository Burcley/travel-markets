export function getInstitutionById(id: string) {
  return CANADIAN_INSTITUTIONS.find((institution) => institution.id === id) || null;
}

export function getCampusById(id: string) {
  return INSTITUTION_CAMPUSES.find((campus) => campus.id === id) || null;
}

export function getCampusesForInstitution(institutionId: string) {
  return INSTITUTION_CAMPUSES.filter(
    (campus) => campus.institutionId === institutionId && campus.active
  );
}

export function getOntarioUniversities() {
  return CANADIAN_INSTITUTIONS.filter(
    (institution) =>
      institution.active &&
      institution.province === "Ontario" &&
      institution.type === "university"
  );
}

export function campusBelongsToInstitution({
  campusId,
  institutionId,
}: {
  campusId: string;
  institutionId: string;
}) {
  const campus = getCampusById(campusId);

  return Boolean(campus && campus.active && campus.institutionId === institutionId);
}
